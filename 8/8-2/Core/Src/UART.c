/**
 * @brief 重定向 printf 函数到 UART1
 * @param ch 要发送的字符
 * @param f 文件指针（未使用）
 * @return 发送的字符
 */
int fputc(int ch, FILE *f) {
  HAL_UART_Transmit(&huart1, (uint8_t *)&ch, 1, HAL_MAX_DELAY); // 将字符通过 UART1 发送
  return ch; // 返回发送的字符
}

